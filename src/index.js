import { app } from "./app.js";
import "dotenv/config";

// Express 4.x не перехватывает необработанные исключения/отклонённые промисы
// из async-обработчиков сам. Node.js по умолчанию завершает процесс на любой
// необработанной ошибке промиса — то есть одна забытая обработка ошибки в
// любом роуте (например, синхронный fs.*Sync без try/catch) кладёт сервис
// целиком для всех пользователей сразу. Логируем и НЕ даём процессу упасть —
// в худшем случае зависнет один конкретный запрос, а не всё приложение.
process.on("unhandledRejection", (reason) => {
  console.error("Необработанный отклонённый промис (процесс НЕ остановлен):", reason);
});
process.on("uncaughtException", (err) => {
  console.error("Необработанное исключение (процесс НЕ остановлен):", err);
});

const port = Number(process.env.PORT || 3001);
app.listen(port, "127.0.0.1", () => {
  console.log(`uchet-server слушает на 127.0.0.1:${port}`);
});
