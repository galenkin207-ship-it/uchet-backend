// Самопроверка buildLeafName (work-types-shared.js) без БД:
//   node scripts/test-build-leaf-name.js
import assert from "node:assert/strict";
import { buildLeafName } from "../src/routes/work-types-shared.js";

const cases = [
  // группа с ":" (конвенция ГЭСН) → «группа вариант»
  ["Трансформатор трехфазный:", "35 кВ мощностью 250 кВ·А", "Трансформатор трехфазный: 35 кВ мощностью 250 кВ·А"],
  // группа без ":" (пользовательский прайс) → «группа: вариант»
  ["Демонтаж бетонного основания толщиной", "до 100 мм", "Демонтаж бетонного основания толщиной: до 100 мм"],
  // пустой вариант → название группы
  ["Демонтаж бетонного основания толщиной", "", "Демонтаж бетонного основания толщиной"],
  ["Демонтаж бетонного основания толщиной", null, "Демонтаж бетонного основания толщиной"],
  ["Демонтаж бетонного основания толщиной", "   ", "Демонтаж бетонного основания толщиной"],
  ["Трансформатор трехфазный:", undefined, "Трансформатор трехфазный:"],
  // вариант равен группе (в т.ч. пустая группа ГЭСН: вариант = наименование)
  ["Устройство кротового дренажа", "Устройство кротового дренажа", "Устройство кротового дренажа"],
  ["Трансформатор трехфазный:", "Трансформатор трехфазный", "Трансформатор трехфазный"],
  // вариант начинается с группы → как есть
  ["Изоляция трубопроводов:", "Изоляция трубопроводов: до 350 мм", "Изоляция трубопроводов: до 350 мм"],
  ["Демонтаж бетона", "Демонтаж бетона толщиной до 100 мм", "Демонтаж бетона толщиной до 100 мм"],
  // регистр, ё/е, пунктуация, лишние пробелы при сравнении
  ["Устройство ЖЁЛОБОВ", "устройство желобов из оцинковки", "устройство желобов из оцинковки"],
  ["Устройство желобов,", "Устройство  желобов   до 5 м", "Устройство желобов до 5 м"],
  // лишние пробелы вокруг и внутри
  ["  Демонтаж   бетона  ", "  до 100   мм ", "Демонтаж бетона: до 100 мм"],
  ["  Трансформатор   трехфазный:  ", " 35 кВ ", "Трансформатор трехфазный: 35 кВ"],
  // начало по границе слова: «Стена» не префикс «Стенами …»
  ["Стена", "Стенами кирпичные", "Стена: Стенами кирпичные"],
  // пустая группа → вариант
  ["", "до 100 мм", "до 100 мм"],
  [null, "до 100 мм", "до 100 мм"],
];

let failed = 0;
for (const [group, variant, expected] of cases) {
  const actual = buildLeafName(group, variant);
  try {
    assert.equal(actual, expected);
  } catch {
    failed += 1;
    console.error(`FAIL buildLeafName(${JSON.stringify(group)}, ${JSON.stringify(variant)})\n  expected: ${JSON.stringify(expected)}\n  actual:   ${JSON.stringify(actual)}`);
  }
}
if (failed) {
  console.error(`${failed} из ${cases.length} кейсов не прошли`);
  process.exit(1);
}
console.log(`OK: ${cases.length} кейсов`);
